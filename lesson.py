from pathlib import Path
import json
import runpy


# Load the sample weather function from the cloned repository.
repo = Path(__file__).resolve().parent / "ai-engineering-from-scratch"

lesson_path = (
    repo
    / "phases"
    / "11-llm-engineering"
    / "09-function-calling"
    / "code"
    / "function_calling.py"
)

lesson = runpy.run_path(str(lesson_path))
get_weather = lesson["get_weather"]


def clean_city(city):
    """Return a cleaned city name, or None for invalid input."""
    if not isinstance(city, str):
        return None

    city = city.strip()

    if not city:
        return None

    return city


def get_validated_weather(city):
    """Validate the city before calling the weather tool."""
    cleaned_city = clean_city(city)

    if cleaned_city is None:
        return {
            "error": True,
            "message": "Invalid city name",
            "code": "INVALID_CITY",
        }

    try:
        return get_weather(city=cleaned_city)
    except ConnectionError:
        return {
            "error" : True,
            "message" : "Weather service is temporarity unavailable.",
            "code" : "WEATHER_UNAVAILABLE"
        }


def dispatch_tool_call(tool_call):
    """Validate a tool request and execute a supported tool."""
    if not isinstance(tool_call, dict):
        return {
            "error": True,
            "message": "Tool request must be an object",
            "code": "INVALID_TOOL_CALL",
        }

    tool_name = tool_call.get("name")

    if tool_name == "get_weather":
        arguments = tool_call.get("arguments")

        if not isinstance(arguments, dict):
            return {
                "error": True,
                "message": "Arguments must be an object",
                "code": "INVALID_ARGUMENTS",
            }

        city = arguments.get("city")
        return get_validated_weather(city)

    return {
        "error": True,
        "message": "Unknown tool",
        "code": "UNKNOWN_TOOL",
    }


def main():
    # These requests are manually written, not generated by a real LLM.
    requests = [
        (
            "Valid city with spaces",
            '{"name": "get_weather", "arguments": {"city": " Tokyo "}}',
        ),
        (
            "Blank city",
            '{"name": "get_weather", "arguments": {"city": "   "}}',
        ),
        (
            "Numeric city",
            '{"name": "get_weather", "arguments": {"city": 123}}',
        ),
        (
            "Unsupported city",
            '{"name": "get_weather", "arguments": {"city": "Atlantis"}}',
        ),
        (
            "Missing city",
            '{"name": "get_weather", "arguments": {}}',
        ),
        (
            "Missing arguments",
            '{"name": "get_weather"}',
        ),
        (
            "Unknown tool",
            '{"name": "send_email", "arguments": {}}',
        ),
        (
            "Malformed JSON",
            '{"name":',
        ),
        (
            "JSON list instead of object",
            '[]',
        ),
        (
            "Empty JSON object",
            '{}',
        ),
    ]

    for label, request_text in requests:
        try:
            tool_call = json.loads(request_text)
        except json.JSONDecodeError:
            result = {
                "error": True,
                "message": "Invalid JSON",
                "code": "INVALID_JSON",
            }
        else:
            result = dispatch_tool_call(tool_call)

        print(f"\n{label}")
        print(json.dumps(result, indent=2, ensure_ascii=False))

def handle_tool_request(tool_name, arguments_text):
    try:
            arguments = json.loads(arguments_text)
    except json.JSONDecodeError:
            return {
                "error": True,
                "message": "Tool arguments are not valid JSON",
                "code": "INVALID_JSON",
            }

    return dispatch_tool_call({
            "name": tool_name,
            "arguments": arguments,
    })


if __name__ == "__main__":
    main()